#!/usr/bin/env node
// Writes src/lib/catalog-logos.ts: the simple-icons paths of the catalog
// entries that have a logo (D-141), so the app takes no icon dependency.
//
//   npm pack simple-icons@16.36.0 && tar xzf simple-icons-16.36.0.tgz
//   node scripts/catalog-logos.mjs package
//
// Keys are catalog slugs (backend/internal/catalog); an entry missing here
// shows its initials.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const VERSION = "16.36.0";
const SLUGS = {
  postgres: "postgresql", mysql: "mysql", mongodb: "mongodb", redis: "redis", rabbitmq: "rabbitmq",
  minio: "minio", phpmyadmin: "phpmyadmin", adminer: "adminer", nginx: "nginx", prometheus: "prometheus",
  grafana: "grafana", "uptime-kuma": "uptimekuma", plausible: "plausibleanalytics", n8n: "n8n",
  ghost: "ghost", umami: "umami",
};

const pkg = process.argv[2];
if (!pkg) throw new Error("usage: catalog-logos.mjs <simple-icons package dir>");
const v = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8")).version;
if (v !== VERSION) throw new Error(`simple-icons ${v}, want ${VERSION}`);
const lines = Object.entries(SLUGS).map(([slug, icon]) => {
  const d = readFileSync(join(pkg, "icons", `${icon}.svg`), "utf8").match(/ d="([^"]+)"/)?.[1];
  if (!d) throw new Error(`no path in ${icon}.svg`);
  return `  ${JSON.stringify(slug)}: ${JSON.stringify(d)},`;
});
writeFileSync(
  new URL("../src/lib/catalog-logos.ts", import.meta.url),
  `// Generated by scripts/catalog-logos.mjs from simple-icons ${VERSION} (CC0): don't edit.\n` +
    `/** A catalog entry's logo, as one 24×24 path, by its slug (D-141). */\n` +
    `export const CATALOG_LOGOS: Record<string, string> = {\n${lines.join("\n")}\n};\n`,
);
